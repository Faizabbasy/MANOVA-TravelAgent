import { writeFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('year demo renders actual history and preserves a Finance-created business transaction', async ({ page, request }, info) => {
  const health = await (await request.get('/api/v1/health')).json()
  expect(health.data.environment).toBe('development')
  expect(health.data.database.engine).toBe('pglite')
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => ['localhost', '127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: /Masuk sebagai .*Finance/i }).click()
  await expect(page).toHaveURL(/localhost:8080\/$/)
  await page.goto('/finance/accounting', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Laporan & Cek Bulanan', exact: true })).toBeVisible()
  await expect(page.getByText('DEMO FIKTIF — MANOVA 12 bulan', { exact: true })).toBeVisible()
  await page.getByLabel('Laba dari tanggal').fill('2025-11-01')
  await page.getByLabel('Sampai / posisi per tanggal').fill('2026-10-22')
  await expect(page.getByRole('region', { name: 'Laba rugi', exact: true })).toContainText('2025-11-01')
  await expect(page.getByText('Memuat laba dan posisi keuangan…', { exact: true })).toHaveCount(0)
  const trial = await (await page.request.get('/api/v1/accounting/trial-balance?asOf=2026-10-22')).json()
  expect(trial.data.balanced).toBe(true)
  expect(trial.data.rows.some((r: { code: string; balanceMinor: string }) => r.code === '4100' && BigInt(r.balanceMinor) !== 0n)).toBe(true)
  await page.screenshot({ path: info.outputPath('year-accounting-1440.png'), fullPage: true })
  await page.getByRole('link', { name: 'Kasbon & Bukti Biaya', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Kasbon & Bukti Biaya', exact: true })).toBeVisible()
  await expect(page.getByText('Riwayat', { exact: true })).toBeVisible()
  const funds = await (await page.request.get('/api/v1/finance/staff-funds')).json()
  expect(funds.data.movements.length).toBeGreaterThan(20)
  expect(funds.data.employees.some((e: { owedToEmployeeMinor: string }) => BigInt(e.owedToEmployeeMinor) > 0n)).toBe(true)
  await page.screenshot({ path: info.outputPath('year-staff-1440.png'), fullPage: true })
  await page.getByRole('link', { name: 'Aset, Pinjaman & Modal', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aset, Pinjaman & Modal', exact: true })).toBeVisible()
  const funding = await (await page.request.get('/api/v1/finance/funding')).json()
  expect(funding.data.assets).toHaveLength(1)
  expect(funding.data.loans.length).toBeGreaterThanOrEqual(1)
  await page.screenshot({ path: info.outputPath('year-funding-1440.png'), fullPage: true })
  const name = `DEMO UAT Persisten ${Date.now()}`
  await page.getByRole('button', { name: 'Catat pinjaman', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('#fd-lender').fill(name)
  await dialog.locator('#fd-terms').fill('TEST_ONLY bukti penyimpanan; bukan pinjaman nyata')
  await dialog.locator('#fd-amount').fill('1000000')
  const saved = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname.includes('/finance/loans'))
  await dialog.getByRole('button', { name: 'Catat pinjaman', exact: true }).click()
  const response = await saved
  expect(response.ok(), await response.text()).toBe(true)
  const result = (await response.json()).data
  await expect(dialog).toHaveCount(0)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByText(name, { exact: true })).toBeVisible()
  await writeFile(info.outputPath('year-demo-proof.json'), JSON.stringify({ name, ...result }, null, 2))
  expect(errors).toEqual([])
})

test('year report settles with actual profit and retains the transaction after a backend restart', async ({ page }, info) => {
  await page.route('**/*', route => ['localhost', '127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: /Masuk sebagai .*Finance/i }).click()
  await expect(page).toHaveURL(/localhost:8080\/$/)
  await page.goto('/finance/accounting', { waitUntil: 'domcontentloaded' })
  await page.getByLabel('Laba dari tanggal').fill('2025-11-01')
  await page.getByLabel('Sampai / posisi per tanggal').fill('2026-10-22')
  const response = await page.request.get('/api/v1/accounting/reports/profit-loss?from=2025-11-01&to=2026-10-22')
  expect(response.ok(), await response.text()).toBe(true)
  const report = (await response.json()).data
  expect(BigInt(report.revenue.totalMinor)).toBeGreaterThan(0n)
  expect(BigInt(report.profitBeforeTaxMinor)).toBeGreaterThan(0n)
  expect(report.netProfitMinor).toBeNull()
  const profitCard = page.getByRole('region', { name: 'Laba rugi', exact: true })
  await expect(profitCard).toContainText('2025-11-01')
  await expect(profitCard).toContainText(report.revenue.totalMinor.replace(/\B(?=(\d{3})+(?!\d))/g, '.'))
  await expect(page.getByText('Memuat laba dan posisi keuangan…', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Laba rugi', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('year-report-settled.png'), fullPage: true })
  const loans = (await (await page.request.get('/api/v1/finance/funding')).json()).data.loans
  expect(loans.some((l: { lender: string }) => l.lender.startsWith('DEMO UAT Persisten '))).toBe(true)
  await writeFile(info.outputPath('year-report-totals.json'), JSON.stringify({ revenueMinor: report.revenue.totalMinor, profitBeforeTaxMinor: report.profitBeforeTaxMinor, netProfitMinor: report.netProfitMinor }, null, 2))
})

test('year bank statement demo shows matched and practice rows and matches without creating money', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => ['localhost', '127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: /Masuk sebagai .*Finance/i }).click()
  await expect(page).toHaveURL(/localhost:8080\/$/)
  const accounts = (await (await page.request.get('/api/v1/finance/accounts')).json()).data
  const bank = accounts.find((a: { code: string }) => a.code === 'DEMO-BCA')
  expect(bank).toBeTruthy()
  const query = `/api/v1/finance/bank-statement-lines?bankAccountId=${bank.id}&from=2026-10-01&to=2026-10-22`
  const lines = (await (await page.request.get(query)).json()).data.lines
  expect(lines.some((l: { status: string }) => l.status === 'matched')).toBe(true)
  const target = lines.find((l: { externalRef: string; status: string; candidates: { exactAmount: boolean }[] }) => l.externalRef.startsWith('DEMO-BANK-TRX-') && l.status === 'unmatched' && l.candidates[0]?.exactAmount)
  expect(target).toBeTruthy()
  const before = (await (await page.request.get(`/api/v1/finance/accounts/${bank.id}`)).json()).data.balance.currentMinor
  const trial = (await (await page.request.get('/api/v1/accounting/trial-balance?asOf=2026-10-22')).json()).data.rows
  await page.goto('/finance/reconciliation', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Cocokkan Rekening Koran', exact: true })).toBeVisible()
  const row = page.locator('section[aria-label="Baris rekening koran"] > div').filter({ hasText: target.externalRef })
  await expect(row.getByText('Belum cocok', { exact: true })).toBeVisible()
  const saved = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === `/api/v1/finance/bank-statement-lines/${target.id}/match`)
  await row.getByRole('button').first().click()
  const response = await saved
  expect(response.ok(), await response.text()).toBe(true)
  expect(response.request().postDataJSON().matches[0].transactionId).toBe(target.candidates[0].transactionId)
  await expect(row.getByText('Cocok', { exact: true })).toBeVisible()
  expect((await (await page.request.get(`/api/v1/finance/accounts/${bank.id}`)).json()).data.balance.currentMinor).toBe(before)
  expect((await (await page.request.get('/api/v1/accounting/trial-balance?asOf=2026-10-22')).json()).data.rows).toEqual(trial)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(row.getByText('Cocok', { exact: true })).toBeVisible()
  await expect(page.getByText('DEMO biaya admin bank belum dicatat', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('year-bank-statement-1440.png'), fullPage: true })
  expect(errors).toEqual([])
})
